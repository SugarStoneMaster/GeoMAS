"""
Memory Schemas.

Pydantic models for agent events:
- RelationshipSummary: Compact bilateral relationship for ~50 tokens per relation
- NotableEvent: World events for ~20 tokens each
- MyAction: Past actions for ~25 tokens each
"""

from enum import Enum
from typing import Optional, List
from pydantic import BaseModel, Field


class EventType(str, Enum):
    """Types of notable events."""
    # Diplomatic events (world news)
    WAR_DECLARED = "WAR_DECLARED"
    PEACE_SIGNED = "PEACE_SIGNED"
    PEACE_REJECTED = "PEACE_REJECTED"
    ALLIANCE_FORMED = "ALLIANCE_FORMED"
    ALLIANCE_UPGRADED = "ALLIANCE_UPGRADED"
    ALLIANCE_DOWNGRADED = "ALLIANCE_DOWNGRADED"
    ALLIANCE_BROKEN = "ALLIANCE_BROKEN"
    ALLIANCE_REJECTED = "ALLIANCE_REJECTED"
    DIPLOMATIC_MESSAGE = "DIPLOMATIC_MESSAGE"
    REQUEST_PEACE = "REQUEST_PEACE"
    PROPOSE_ALLIANCE = "PROPOSE_ALLIANCE"
    
    # Military events (world news)
    ATTACK = "ATTACK"
    COMBAT_RESULT = "COMBAT_RESULT"
    TERRITORY_LOST = "TERRITORY_LOST"
    TERRITORY_GAINED = "TERRITORY_GAINED"
    NUCLEAR_STRIKE = "NUCLEAR_STRIKE"
    TROOPS_MOBILIZED = "TROOPS_MOBILIZED"  # Troops moved to border
    
    # Economic events (world news)
    TRADE_DEAL = "TRADE_DEAL"
    GENERAL_STRIKE = "GENERAL_STRIKE"
    
    # Internal crisis events (generated by engine, not actions)
    ECONOMIC_CRISIS = "ECONOMIC_CRISIS"
    CIVIL_UNREST = "CIVIL_UNREST"
    
    # Global Scenarios
    GLOBAL_SCENARIO = "GLOBAL_SCENARIO"

# Base Importance Scores for Salience Calculation
